use core::ops::Index;

use bytemuck::{NoUninit, Pod, Zeroable};

use crate::context;

/// Maximum amount of content a file can store in bytes.
pub const CONTENT_SIZE: usize = 8192;
/// Size of a UUID in bytes.
pub const UUID_SIZE: usize = 16;
/// Maximum size of a file name in bytes.
pub const NAME_SIZE: usize = 32;

/// Container for the file name.
#[derive(Debug, Copy, Clone, Pod, Zeroable)]
#[repr(transparent)]
pub struct FileName(pub [u8; NAME_SIZE]);

/// Container for the file UUID.
#[derive(Debug, Copy, Clone, Pod, Zeroable)]
#[repr(transparent)]
pub struct UUID(pub [u8; UUID_SIZE]);

/// Container for file metadata, including the number slot the file is located in the FAT, the ID of the
/// group it belongs to, and it's name.
#[derive(Debug, Copy, Clone, Pod, Zeroable)]
#[repr(C, packed)]
pub struct FileMeta {
    pub slot: u8,
    pub group: u16,
    pub name: FileName,
}

/// The file's data, metadata, and cryptographic metadata collected in one struct.
#[repr(C)]
#[derive(Debug, Clone, Copy)]
/// Signed file data. Includes ciphertext, required file metadata, as well as G^n, nonce, and tag for decryption.
pub struct ProtectedFileData {
    /// A random number generated by the TRNG for encryption.
    pub nonce: [u8; 24],
    /// The tag created by Poly1305 during ChaCha20 encryption.
    pub tag: [u8; 16],
    /// The public key associated with the file for Diffie-Hellman key exchange.
    pub gn: [u8; 32],
    /// The file's name.
    pub name: FileName,
    /// The file's UUID.
    pub uuid: UUID,
    /// The file's owning group.
    pub group: u16,
    /// The length of the file's contents.
    pub contents_length: u16,
    /// The contents of the file, which should be encrypted.
    pub contents: [u8; CONTENT_SIZE],
}

impl ProtectedFileData {
    /// Initialize self, setting all fields to 0.
    pub const fn empty() -> Self {
        Self {
            nonce: [0; 24],
            tag: [0; 16],
            gn: [0; 32],
            name: FileName([0; NAME_SIZE]),
            uuid: UUID([0; UUID_SIZE]),
            group: 0,
            contents_length: 0,
            contents: [0; CONTENT_SIZE],
        }
    }
}
unsafe impl Zeroable for ProtectedFileData {
    /// Zero out the struct.
    fn zeroed() -> Self {
        Self::empty()
    }
}
unsafe impl Pod for ProtectedFileData {}
/// All data associated with a file are signed together and stored alongside that signature. 
#[repr(C)]
#[derive(Debug, Clone, Copy)]

/// Layout of a file. Includes state(EMPTY or FULL), ed25519 signature, and signed data.
pub struct File {
    /// The state describing whether or not data is currently being stored.
    pub state: u64,
    /// The signature of all data associated with a file.
    pub signature: [u8; 64],
    /// All data associated with a file, including its contents, metadata, and cryptographic
    /// metadata.
    pub protected: ProtectedFileData,
    _pad: [u8; 4], // pad to a multiple of 8 as required by FlashEntry
}

impl File {
    /// Enumeration for an empty File.
    pub const EMPTY: u64 = 0xd8b1f12cd454a41d;
    /// Enumeration for filled File.
    pub const FULL: u64 = 0xc0aa73e0c260426e;
    /// Initialize self, setting all fields to zero.
    pub const fn empty() -> Self {
        Self {
            state: File::EMPTY,
            signature: [0; _],
            protected: ProtectedFileData::empty(),
            _pad: [u8; 4],
        }
    }
    /// Check a file's state, returning whether or not data is stored in the file.
    pub(crate) fn is_full(&self) -> bool {
        self.state == File::FULL
    }
}
unsafe impl Zeroable for File {
    /// Zero out the struct.
    fn zeroed() -> Self {
        Self::empty()
    }
}
unsafe impl Pod for File {}

/// A FAT Entry describes the location and amount of space in flash where a File is to be
/// contained; each entry has a differentiating UUID.
#[repr(C)]
#[derive(Clone, Copy, Debug)]

/// File allocation table entry used by the eCTF bootloader.
pub struct FatEntry {
    /// A FAT entry's unique UUID.
    pub uuid: UUID,
    /// The length of a FAT entry.
    pub length: u16,
    /// The padding after the length of a FAT Entry.
    pub padding: u16,
    /// The address of the FAT Entry in flash.
    pub addr: u32,
}

/// The FAT Table indexes all FatEntries on the flash.
#[derive(Debug, Clone, Copy)]

/// File allocation table used by the eCTF bootloader.
pub struct FatTable {
    /// The FAT stores a maximum of eight files, and thus has eight FAT entries.
    pub entries: [FatEntry; 8],
}

impl Index<usize> for FatTable {
    type Output = FatEntry;
    /// Retrieve a FatEntry by its index on the FatTable.
    fn index(&self, index: usize) -> &Self::Output {
        &self.entries[index]
    }
}
unsafe impl NoUninit for FatTable {}

/// The FileSlot contains a file and a identifying magic value to be stored at a corresponding FAT
/// entry.
#[repr(align(1024), C)]
#[derive(Copy, Clone)]
pub struct FileSlot {
    /// The (encrypted) file to be stored.
    pub file: File,
    // A value to identify where the File ends.
    pub magic: u64,
}

/// Forces "filled" files and FAT to appear in flash on first boot.
#[unsafe(link_section = ".files.default")]
#[unsafe(no_mangle)]
pub static __FILES: [FileSlot; 8] = [FileSlot {
    file: File::empty(),
    magic: context::FLASH_MAGIC,
}; 8];

