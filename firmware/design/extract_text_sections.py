#!/usr/bin/env python3
"""
Build firmware, then print linker .text.* sections and GC-removed .text.* sections.

This script assumes required env vars (e.g., BUILD_SEED, HSM_PIN, PERMISSIONS,
LOCAL_SECRETS_FILE) are already set in the caller environment.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import shlex
import subprocess
import sys


DEFAULT_BUILD_CMD = (
    "cargo rustc --release --target thumbv6m-none-eabi -- "
    "-C link-arg=-Wl,-Map=target/design.map "
    "-C link-arg=-Wl,--print-gc-sections"
)


def run_build(command: str) -> tuple[int, str]:
    proc = subprocess.run(
        command,
        shell=True,
        check=False,
        text=True,
        capture_output=True,
    )
    build_output = f"{proc.stdout}\n{proc.stderr}"
    return proc.returncode, build_output


def extract_all_text_sections(map_text: str) -> list[str]:
    sections = set(re.findall(r"^\s*(\.text\.[^\s]+)", map_text, flags=re.MULTILINE))
    return sorted(sections)


def extract_gc_removed_sections(build_output: str) -> list[str]:
    removed = set(
        re.findall(r"removing unused section '(\.text\.[^']+)'", build_output)
    )
    return sorted(removed)


def print_section_list(title: str, sections: list[str]) -> None:
    print(f"{title} ({len(sections)}):")
    for section in sections:
        print(section)
    print()


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Build firmware and print .text.* and GC-removed .text.* sections."
    )
    parser.add_argument(
        "--build-cmd",
        default=DEFAULT_BUILD_CMD,
        help="Build command to run (default uses cargo rustc with map + gc-sections).",
    )
    parser.add_argument(
        "--map-file",
        default="target/design.map",
        help="Path to linker map file generated by the build command.",
    )
    args = parser.parse_args()

    print(f"Running build command:\n  {args.build_cmd}\n")
    returncode, build_output = run_build(args.build_cmd)

    # Keep raw build output in a Python string and also write it for inspection.
    build_output_path = pathlib.Path("target/build_sections_output.log")
    build_output_path.parent.mkdir(parents=True, exist_ok=True)
    build_output_path.write_text(build_output)
    print(f"Saved build output string to: {build_output_path}\n")

    if returncode != 0:
        print(f"Build failed with exit code {returncode}.", file=sys.stderr)
        print("First 200 lines of captured build output:", file=sys.stderr)
        for line in build_output.splitlines()[:200]:
            print(line, file=sys.stderr)
        return returncode

    map_path = pathlib.Path(args.map_file)
    if not map_path.exists():
        print(
            f"Map file not found at {map_path}. "
            "Use --map-file or ensure build command emits -Map.",
            file=sys.stderr,
        )
        return 2

    map_text = map_path.read_text()
    all_sections = extract_all_text_sections(map_text)
    gc_removed_sections = extract_gc_removed_sections(build_output)
    gc_kept_estimate = sorted(set(all_sections) - set(gc_removed_sections))

    print_section_list("All .text.* sections from map", all_sections)
    print_section_list("GC removed .text.* sections", gc_removed_sections)
    print_section_list("Estimated kept .text.* sections", gc_kept_estimate)

    print("Summary:")
    print(f"- build_cmd: {shlex.quote(args.build_cmd)}")
    print(f"- map_file: {map_path}")
    print(f"- all_sections: {len(all_sections)}")
    print(f"- gc_removed_sections: {len(gc_removed_sections)}")
    print(f"- kept_estimate: {len(gc_kept_estimate)}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
